#!/usr/bin/env node
// scripts/gen-routes.mjs
// Makers 的 Node 函数是「文件即路由」：cloud-functions/api/alive.js -> /api/alive。
// 之前只放了一个 [[default]].js 兜底，控制台里「函数」列表是空的 —— 说明它不被当函数扫描。
// 这个脚本按 Hono 实际注册的路由，生成一一对应的函数文件。
import { writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import app from '../src/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const cfDir = join(root, 'cloud-functions');

// 清掉旧的兜底文件（如果平台不认，会占位）
if (existsSync(cfDir)) rmSync(cfDir, { recursive: true, force: true });

const byPath = new Map();
for (const r of app.routes) {
  if (!r.method || r.method === 'ALL') continue;
  const m = r.method.toLowerCase();
  const p = r.path;
  if (!byPath.has(p)) byPath.set(p, new Set());
  byPath.get(p).add(m);
}

let written = 0;
for (const [path, methods] of byPath) {
  // /api/ciphers/:id -> cloud-functions/api/ciphers/[id].js
  const segs = path.split('/').filter(Boolean);
  const fileSegs = segs.map((s) => (s.startsWith(':') ? `[${s.slice(1)}]` : s));
  const dirSegs = fileSegs.slice(0, -1);
  const fileName = `${fileSegs.at(-1)}.js`;
  const dir = join(cfDir, ...dirSegs);
  mkdirSync(dir, { recursive: true });

  const depth = dirSegs.length + 1; // + cloud-functions 这一层
  const rel = '../'.repeat(depth) + 'src/makers.js';

  const exports = [...methods]
    .map((m) => `export const onRequest${m[0].toUpperCase()}${m.slice(1)} = (ctx) => app(ctx);`)
    .join('\n');

  writeFileSync(
    join(dir, fileName),
    `// generated by scripts/gen-routes.mjs — route: ${[...methods].join(',').toUpperCase()} ${path}\nimport app from '${rel}';\n${exports}\n`,
    'utf8',
  );
  written += 1;
}

console.log(`生成 ${written} 个函数文件到 cloud-functions/（来自 ${app.routes.length} 条注册）`);
